# Introdução aos operadores aritméticos
 
# adição
adicao = 2 + 2
print(f'Resultado: {adicao}')
# Substração
substracao = 105 - 210
print(f'Resultado: {substracao}')
# multipplicação
multiplicacao = 5 * 104
print(f'Resultado: {multiplicacao}')
# divisão comum (retorna float)
division_comun = 52 / 6
print(f'Resultado: {division_comun}')
# divisão inteira
divisao_inteira = 52 // 6
print(f'Resultado: {divisao_inteira}')
#Resto de divisão
resto_divisao = 52 % 6
print(f'Resultado: {resto_divisao}')
#Exponenciação
exponenciacao = 52 ** 6
print(f'Resultado: {exponenciacao}')